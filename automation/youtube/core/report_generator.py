"""
Publishing Report Generator Module.
Generates comprehensive Markdown and CSV post-upload publication audit summaries.
"""

import csv
import logging
from datetime import datetime
from pathlib import Path
from typing import List, Optional

from database.models import UploadJob

logger = logging.getLogger(__name__)


class ReportGenerator:
    """Creates formatted Markdown and CSV upload reports."""

    @staticmethod
    def generate_markdown_report(
        jobs: List[UploadJob],
        channel_name: str,
        channel_id: str,
        playlist_title: str,
        playlist_id: str,
        output_path: str
    ) -> str:
        """Generates a professional Markdown audit report."""
        p = Path(output_path)
        p.parent.mkdir(parents=True, exist_ok=True)

        lines: List[str] = [
            "# 🎬 Codealytica YouTube Publishing Audit Report",
            f"*Generated on: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}*",
            "",
            "## 📌 Channel & Playlist Summary",
            f"- **Channel Name:** `{channel_name}`",
            f"- **Channel ID:** `{channel_id}`",
            f"- **Target Playlist:** [{playlist_title}](https://www.youtube.com/playlist?list={playlist_id})",
            f"- **Playlist ID:** `{playlist_id}`",
            f"- **Default Video Privacy:** `PRIVATE` *(Strict Codealytica Policy)*",
            "",
            "## 📊 Published Videos Ledger",
            "",
            "| # | Lesson Title | Video ID | YouTube Link | Thumbnail | Subtitles | Playlist | Status |",
            "|---|--------------|----------|--------------|-----------|-----------|----------|--------|",
        ]

        total_bytes = 0
        completed_count = 0

        for job in jobs:
            meta = job.video_metadata
            yt_id = job.youtube_video_id or "N/A"
            yt_link = f"[{yt_id}]({job.youtube_video_url})" if job.youtube_video_url else "N/A"
            thumb_status = "✅" if job.thumbnail_status == "completed" else "❌" if job.thumbnail_status == "failed" else "⚠️ Skipped"
            sub_status = "✅" if job.caption_status == "completed" else "❌" if job.caption_status == "failed" else "⚠️ Skipped"
            pl_status = "✅" if job.playlist_status == "completed" else "❌" if job.playlist_status == "failed" else "⚠️ Skipped"

            stat_str = getattr(job.status, "value", str(job.status))
            status_icon = "✅ Done" if stat_str == "completed" else f"⚠️ {stat_str.capitalize()}"

            clean_title = meta.title.replace("|", "-")
            lines.append(
                f"| {meta.lesson_number:02d} | {clean_title} | `{yt_id}` | {yt_link} | {thumb_status} | {sub_status} | {pl_status} | {status_icon} |"
            )

            total_bytes += meta.file_size_bytes
            if stat_str in ["completed", "uploaded"]:
                completed_count += 1

        total_mb = total_bytes / (1024 * 1024)
        quota_estimate = completed_count * 1600 + (completed_count * 50) + 100

        lines.extend([
            "",
            "## 📈 Execution Metrics",
            f"- **Total Videos Processed:** {len(jobs)}",
            f"- **Successfully Completed:** {completed_count}/{len(jobs)}",
            f"- **Total Media Size:** {total_mb:.2f} MB",
            f"- **Estimated YouTube API Quota Consumed:** ~{quota_estimate:,} / 10,000 units",
            "",
            "---",
            "*Report automatically generated by Codealytica YouTube Publisher v1.0.0*",
        ])

        report_content = "\n".join(lines)
        with open(p, "w", encoding="utf-8") as f:
            f.write(report_content)

        logger.info("Markdown upload report saved to %s", output_path)
        return report_content

    @staticmethod
    def generate_csv_report(jobs: List[UploadJob], output_path: str) -> None:
        """Exports upload records to CSV."""
        p = Path(output_path)
        p.parent.mkdir(parents=True, exist_ok=True)

        with open(p, "w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            writer.writerow([
                "Lesson", "Title", "YouTube ID", "YouTube URL", "Privacy",
                "Thumbnail Status", "Subtitle Status", "Playlist Status",
                "File Size (Bytes)", "SHA256 Hash", "Overall Status"
            ])

            for job in jobs:
                meta = job.video_metadata
                priv_str = getattr(meta.privacy_status, "value", str(meta.privacy_status))
                stat_str = getattr(job.status, "value", str(job.status))
                writer.writerow([
                    meta.lesson_number,
                    meta.title,
                    job.youtube_video_id or "",
                    job.youtube_video_url or "",
                    priv_str,
                    job.thumbnail_status,
                    job.caption_status,
                    job.playlist_status,
                    meta.file_size_bytes,
                    meta.file_hash_sha256,
                    stat_str
                ])

        logger.info("CSV upload report saved to %s", output_path)
